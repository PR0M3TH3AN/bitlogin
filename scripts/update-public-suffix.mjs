#!/usr/bin/env node
// Compile the Public Suffix List into packages/widget/src/embedded/publicSuffixList.ts (docs/site-family.md SF3).
//
//   curl -sS --fail -o /some/new/dir/public_suffix_list.dat https://publicsuffix.org/list/public_suffix_list.dat
//   node scripts/update-public-suffix.mjs /some/new/dir/public_suffix_list.dat
//
// Pull the list only from publicsuffix.org, as the list itself asks. The output is data: rules, one per line,
// lower case, every label in its ASCII (punycode) form, split into the ICANN and the private sections. The
// file's version, commit and SHA-256 are written into the output, so a review can tell which list it is.
// Changing the list changes which sites can share one Allow: it goes through review like any other release.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/update-public-suffix.mjs <path to public_suffix_list.dat>");
  process.exit(2);
}
const bytes = readFileSync(source);
const text = bytes.toString("utf8");
const sha256 = createHash("sha256").update(bytes).digest("hex");
const version = /^\/\/ VERSION: (\S+)$/mu.exec(text)?.[1] ?? "unknown";
const commit = /^\/\/ COMMIT: ([0-9a-f]+)$/mu.exec(text)?.[1] ?? "unknown";

const sections = { icann: [], private: [] };
let section = null;
for (const raw of text.split("\n")) {
  const line = raw.trim();
  if (line === "// ===BEGIN ICANN DOMAINS===") section = "icann";
  else if (line === "// ===BEGIN PRIVATE DOMAINS===") section = "private";
  else if (line.startsWith("// ===END")) section = null;
  if (!section || !line || line.startsWith("//")) continue;
  // A rule is the first word on its line.
  let rule = line.split(/\s/u)[0];
  let prefix = "";
  if (rule.startsWith("!")) {
    prefix = "!";
    rule = rule.slice(1);
  }
  if (rule.startsWith("*.")) {
    prefix += "*.";
    rule = rule.slice(2);
  }
  if (rule.includes("*")) throw new Error(`A wildcard this compiler does not know: ${line}`);
  const ascii = domainToASCII(rule);
  if (!ascii || !/^[a-z0-9.-]+$/u.test(ascii)) throw new Error(`Not a domain: ${line}`);
  sections[section].push(prefix + ascii);
}
if (sections.icann.length < 5000 || sections.private.length < 1000) throw new Error("That does not look like the whole list.");

const out = `// Generated by scripts/update-public-suffix.mjs. Do not edit by hand.
//
// The Public Suffix List, https://publicsuffix.org/ (Mozilla Public License 2.0).
// Version ${version}, commit ${commit}.
// SHA-256 of the file it was made from: ${sha256}.
// ${sections.icann.length} ICANN rules and ${sections.private.length} private rules, in ASCII.

export const PUBLIC_SUFFIX_VERSION = ${JSON.stringify(version)};

export const PUBLIC_SUFFIX_ICANN = ${JSON.stringify(sections.icann.join("\n"))};

export const PUBLIC_SUFFIX_PRIVATE = ${JSON.stringify(sections.private.join("\n"))};
`;
const target = resolve(dirname(fileURLToPath(import.meta.url)), "../packages/widget/src/embedded/publicSuffixList.ts");
writeFileSync(target, out);
console.log(`Wrote ${target}: ${version}, ${sections.icann.length} + ${sections.private.length} rules, ${out.length} bytes.`);
